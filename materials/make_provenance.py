"""Render materials/PROVENANCE.md from the materials databases.

One row per material: the parameters actually used, the declared I3
convention, the I3 provenance class, and where the value came from. Plain
Markdown, no LaTeX and no bibliography dependency -- the source strings are
reproduced as the database records them, so this file cannot drift from what
the simulation reads. A file table with the sha256 of every database in this
directory and its subfolders comes first, so the hashes quoted in the paper and
in ENVIRONMENT_MANIFEST.json can be checked against the files themselves.

Run:  python3 make_provenance.py
"""
from __future__ import annotations
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DBS = [("Base database", "pli_materials.json"),
       ("VIP-Man atlas extension", "pli_materials_vipman.json")]
PREVIOUS = "previous"
RUNTIME_FIELDS = ("tau_TE_ns", "I3", "I3_convention", "aliases")

# What each file is. Hashes are computed, never typed.
ROLE = {
    "pli_materials.json": "current base database (version 8)",
    "pli_materials_vipman.json": "current VIP-Man atlas extension (version 8)",
    "previous/pli_materials.json": "previous base database (version 7)",
    "previous/pli_materials_vipman.json": "previous VIP-Man atlas extension (version 7)",
    "variants/r2c_equal_yield_materials.json":
        "matched-yield core-shell arms: version 8 with I3 = 0.2625 for every "
        "o-Ps-intensity entry (made by variants/make_r2c_materials.py)",
    "variants/r2a_equal_tau_materials.json":
        "null control of the core-shell transport arms: tau forced to 2.0 ns for "
        "adipose_moskal2023 and brain_tumor_moskal2024 (made by "
        "simulation/macros/make_core_shell.py from the database of 2026-08-13)",
    "variants/lookup_baseline.json":
        "lookup arm of the wet-XAD-4 comparison: the pre-Tao-Eldrup constant "
        "lifetime table with flat I3 = 0.35",
}

# sha256 of the files the runs used. They differ from the shipped files only in one reworded phrase of the
# "comment" field of the XAD4_water entry, which the loader does not read. Recorded at run time (simulation/RUNS.json).
AS_USED = {
    "pli_materials.json": "23f607ea14c591722ab72864c9e55ea34abf5b80a87a295a7605a23879e790e4",
    "pli_materials_vipman.json": "1e59f1cfe6c4e3ce42a4825e3830289616e6d774a8a9fcef17a1a1a97198da62",
    "previous/pli_materials.json": "f6d5a53ca33ed6d371160c595d7ebfcf794e64fbd788f277881b1fb5a3aab3a3",
    "previous/pli_materials_vipman.json": "09e75eee2ffaff9b8258f240e457c22fa9facfd8768bcbb51420fc9852f429e2",
    "variants/r2a_equal_tau_materials.json": "0738bcca0ff754d35ce63f2fa75ed4eca9649cecbf5bd60fd0fea276f8b595c0",
    "variants/r2c_equal_yield_materials.json": "25e3441c170cdb12bebf35abfbe6b76b912eb98164dc8890fbc66ca7ad2f507c",
}

CLASS_LEGEND = [
    ("M", "o-Ps intensity measured in the same fit and on the same specimen as the lifetime"),
    ("A", "o-Ps intensity fixed by assumption in the source"),
    ("E", "project estimate, or a measurement on another specimen or in another source"),
]


def short(s, n=64):
    s = " ".join(str(s or "").split())
    return s if len(s) <= n else s[:n - 1] + "…"


def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def all_dbs():
    files = sorted(HERE.glob("*.json")) + sorted(HERE.glob("*/*.json"))
    return [f.relative_to(HERE).as_posix() for f in files]


def is_structural(m):
    flag = "fallback_value_made_explicit"
    return m.get("I3_flag") == flag or m.get("I3_flag_legacy") == flag


out = ["# Material parameter provenance", "",
       "Generated by `make_provenance.py` from the databases in this directory.",
       "Do not edit by hand: edit the JSON and re-run.", "",
       "`I3_convention` is **required** for every entry. `ops_intensity` means the",
       "source reports the o-Ps intensity directly, as a PALS three-component",
       "decomposition does, and the loader multiplies by 4/3 so that P(o-Ps) equals",
       "the quoted I3 exactly. `total_formation` means the source reports the total",
       "positronium formation probability and the value is used unconverted. The two",
       "differ by a factor 4/3, so an entry that omits the field is a hard error",
       "rather than a default.", "",
       "## Files", "",
       "| file | sha256 | entries | entries without `I3_convention` | role |",
       "|---|---|---|---|---|"]
for rel in all_dbs():
    p = HERE / rel
    d = json.loads(p.read_text())
    mats = d.get("materials", [])
    nmiss = sum(1 for m in mats if "I3_convention" not in m)
    out.append(f"| `{rel}` | `{sha(p)}` | {len(mats)} | {nmiss} | {ROLE.get(rel, '')} |")
out += ["",
        "The paper, `simulation/RUNS.json` and the registration records quote the hashes",
        "of the files the runs used. The shipped files differ from those only in one",
        "reworded phrase of the `comment` field of the `XAD4_water` entry, which the",
        "loader does not read. Every runtime field is identical.", "",
        "| file | sha256 of the file the runs used |", "|---|---|"]
out += [f"| `{rel}` | `{h}` |" for rel, h in AS_USED.items()]
out += ["",
        "`variants/make_r2c_materials.py` run on the shipped version 8 writes the shipped",
        "matched-yield file except for the source hash quoted in its `_r2c` note, which",
        "names the file the runs used."]
out += ["",
        "A file with entries that lack `I3_convention` cannot be loaded by the",
        "physics in this release, which stops on such an entry. Those files are kept",
        "as the record of what an earlier build was given, not as inputs for this one.",
        ""]

# what changed from the previous version, computed from the files
cur = json.loads((HERE / DBS[0][1]).read_text())
notes_v8 = cur.get("_notes_v8")
out += ["## Version 8 against version 7", ""]
if notes_v8:
    out += ["The database records the change as follows:", "", "> " + " ".join(notes_v8.split()), ""]
for title, fn in DBS:
    new = {m["name"]: m for m in json.loads((HERE / fn).read_text())["materials"]}
    old = {m["name"]: m for m in json.loads((HERE / PREVIOUS / fn).read_text())["materials"]}
    changed = sorted(n for n in new if n in old
                     and any(new[n].get(k) != old[n].get(k) for k in RUNTIME_FIELDS))
    added = sorted(set(new) - set(old))
    removed = sorted(set(old) - set(new))
    kc = (json.loads((HERE / fn).read_text()).get("constants", {}).get("k_O2_ns_mmHg"),
          json.loads((HERE / PREVIOUS / fn).read_text()).get("constants", {}).get("k_O2_ns_mmHg"))
    out.append(f"* `{fn}`: entries whose runtime fields ({', '.join(RUNTIME_FIELDS)}) "
               f"differ from `{PREVIOUS}/{fn}`: "
               + (", ".join(f"`{n}`" for n in changed) if changed else "none")
               + (f"; added: {', '.join(added)}" if added else "")
               + (f"; removed: {', '.join(removed)}" if removed else "")
               + f". `k_O2_ns_mmHg` {kc[1]:g} -> {kc[0]:g}.")
out += ["",
        "Only `tau_TE_ns`, `I3`, `I3_convention` and `aliases` (with the entry",
        "name) enter the simulated physics. The loader also reads `R_nm`,",
        "`pO2_mmHg`, `tau_pub_ns` and the `constants` block, but only prints them,",
        "so every material not listed above behaves identically under version 7",
        "and version 8.", "",
        "Release v1.0.1 shipped copies of version 7 whose provenance text had been",
        "reworded (`pli_materials.json` sha256 302f2645..., `pli_materials_vipman.json`",
        "a44c09b6...). Their numbers equal `previous/`. They are not shipped any more:",
        "version 8 carries every field they carry, adds `I3_provenance_class` and",
        "`I3_flag_legacy`, and corrects I3 and lifetime attributions that the v1.0.1",
        "copies still give (the Mahmoud 2024 and Zgardzinska 2020 entries).", ""]

out += ["## I3 provenance class", "",
        "| class | meaning |", "|---|---|"]
out += [f"| {c} | {t} |" for c, t in CLASS_LEGEND]
out.append("")

for title, fn in DBS:
    d = json.loads((HERE / fn).read_text())
    mats = d["materials"]
    out += [f"## {title} — `{fn}`", "",
            f"{len(mats)} materials.", "",
            "| material | R (nm) | pO2 (mmHg) | I3 | convention | class | tau_eff (ns) | source |",
            "|---|---|---|---|---|---|---|---|"]
    for m in sorted(mats, key=lambda x: x["name"].lower()):
        out.append("| `{}` | {} | {} | {} | {} | {} | {} | {} |".format(
            m["name"],
            f'{m.get("R_nm", 0):.4f}' if m.get("R_nm") else "n/a",
            f'{m.get("pO2_mmHg", 0):.1f}',
            f'{m.get("I3", 0):.3f}',
            m.get("I3_convention", "**MISSING**"),
            m.get("I3_provenance_class", "n/a"),
            f'{m.get("tau_TE_ns", 0):.4f}',
            short(m.get("tau_source"))))
    out.append("")

    struct = [m for m in mats if is_structural(m)]
    if struct:
        out += ["### Structural materials", "",
                "These are detector and world-volume materials, not phantom",
                "components. Positrons do reach them, so they need lifetime and",
                "formation values; earlier versions supplied those from an implicit",
                "code default. They are declared explicitly here with the same",
                "values, so the assumption is visible and can be argued with. Their",
                "annihilations fall outside any phantom volume and are removed by the",
                "geometric selection in the analysis.", ""]
        for m in struct:
            out.append(f"* `{m['name']}` — tau_eff {m['tau_TE_ns']:.2f} ns, "
                       f"I3 {m['I3']:.2f} ({m['I3_convention']})")
        out.append("")

(HERE / "PROVENANCE.md").write_text("\n".join(out) + "\n")
print(f"wrote {HERE/'PROVENANCE.md'}")
