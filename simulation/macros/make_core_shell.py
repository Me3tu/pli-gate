"""R2 input generator: concentric two-material phantom macros + equal-tau JSON.

Geometry (identical for every arm and both material pairs, so nothing is
tuned per arm):
    shell : cylinder Rmax = 60 mm, height = 100 mm, material 2
    core  : cylinder Rmax = 10 mm, height = 100 mm, material 1, daughter of
            shell, source CONFINED to it
    boundary separation from the source axis: 10 mm (the Sc-44 positron CSDA
    range in soft tissue is ~2-3 mm, so migration is a boundary-layer effect,
    not a whole-volume one)

Arms are selected at RUNTIME by PLI_LIFETIME_MODE (no geometry change):
    (i)   transport : tau from the ANNIHILATION material   [default physics]
    (ii)  source    : tau from the EMISSION material       [source-attached]
    (iii) fixed     : one global tau (PLI_FIXED_TAU_NS)    [lookup table]

Because GetLifetime consumes no random numbers, arms (i) and (ii) run the
SAME transport with the SAME random stream and differ only in the tau applied
to each annihilation. The comparison is therefore paired event-by-event, which
removes transport noise entirely. (The 3-gamma channel decision can diverge in
~0.2 % of events because its probability depends on tau. Immaterial.)

Material pairs, both drawn from the already-validated Sim-1 calibration set
(so the tau values and material database entries are the ones the paper
already uses). Neither pair was selected for effect size:
    A : core adipose_moskal2023 (2.72 ns) / shell brain_tumor_moskal2024 (1.77) -> dtau 0.95
    B : core adipose_avachat2024 (2.54 ns) / shell water_shibuya2020_n2 (1.9215) -> dtau 0.62
"""
from __future__ import annotations
import json
from pathlib import Path

# v1.1.0: paths relative to the release, GATE aliases resolved at run time
ROOT = Path(__file__).resolve().parents[2]          # release root
HERE = Path(__file__).resolve().parent              # simulation/macros/
PH2B = "{PLI_SIM}/geometry/materials_pli_phase2b.db"

PAIRS = {
    "A": dict(core="adipose_moskal2023",  shell="brain_tumor_moskal2024",
              tau_core=2.72, tau_shell=1.77),
    "B": dict(core="adipose_avachat2024", shell="water_shibuya2020_n2",
              tau_core=2.54, tau_shell=1.9215),
}
R_CORE_MM, R_SHELL_MM, HEIGHT_MM = 10.0, 60.0, 100.0

MACRO = """# SPDX-License-Identifier: LGPL-3.0-only
# Copyright (C) 2026 Dhritman Dhar and German Cancer Research Center (DKFZ)
# Paths (release v1.1.0): the aliases below are read from environment variables,
# set by simulation/runner/paths.sh or by hand. See simulation/README.md.
/control/getEnv PLI_SIM
/control/getEnv PLI_SCANNER_MACRO
# ==========================================================================
# R2 transport-novelty phantom, pair {pair}: core {core} / shell {shell}
# Generated by make_r2_inputs.py (referee response R2). Arms are selected at
# runtime via PLI_LIFETIME_MODE. The geometry is identical for every arm.
# ==========================================================================
/control/verbose 0
/run/verbose 0
/event/verbose 0
/tracking/verbose 0

/gate/geometry/setMaterialDatabase {mat_db_main}
/gate/geometry/setMaterialDatabase {mat_db_ph2b}

# ── Scanner (Biograph Vision Quadra) ──────────────────────────────────────
/control/execute {quadra}

# ── Phantom: concentric cylinders, source confined to the core ────────────
/gate/world/daughters/name r2_shell
/gate/world/daughters/insert cylinder
/gate/r2_shell/setMaterial {shell}
/gate/r2_shell/geometry/setRmax {r_shell} mm
/gate/r2_shell/geometry/setHeight {height} mm
/gate/r2_shell/placement/setTranslation 0 0 0 mm
/gate/r2_shell/vis/setVisible true
/gate/r2_shell/vis/setColor blue

/gate/r2_shell/daughters/name r2_core
/gate/r2_shell/daughters/insert cylinder
/gate/r2_core/setMaterial {core}
/gate/r2_core/geometry/setRmax {r_core} mm
/gate/r2_core/geometry/setHeight {height} mm
/gate/r2_core/placement/setTranslation 0 0 0 mm
/gate/r2_core/vis/setVisible true
/gate/r2_core/vis/setColor red

/gate/r2_shell/attachPhantomSD
/gate/r2_core/attachPhantomSD

# ── Physics ───────────────────────────────────────────────────────────────
/gate/physics/addPhysicsList PLI_Physics
/gate/physics/Gamma/SetCutInRegion    world 1 mm
/gate/physics/Electron/SetCutInRegion world 1 mm
/gate/physics/Positron/SetCutInRegion world 1 mm
# Fine cuts in the phantom so the positron range (which drives migration
# across the boundary) is transported, not truncated by the production cut.
/gate/physics/Gamma/SetCutInRegion    r2_core  0.1 mm
/gate/physics/Electron/SetCutInRegion r2_core  0.1 mm
/gate/physics/Positron/SetCutInRegion r2_core  0.1 mm
/gate/physics/Gamma/SetCutInRegion    r2_shell 0.1 mm
/gate/physics/Electron/SetCutInRegion r2_shell 0.1 mm
/gate/physics/Positron/SetCutInRegion r2_shell 0.1 mm

/gate/run/initialize

# ── Digitizer: Biograph Vision Quadra (identical to Sim-1) ────────────────
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/insert adder
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/insert readout
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/readout/setDepth 1
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/insert energyResolution
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/energyResolution/fwhm 0.101
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/energyResolution/energyOfReference 511 keV
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/insert timeResolution
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/timeResolution/fwhm 214 ps
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/insert energyFraming
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/energyFraming/setMin 435 keV
/gate/digitizerMgr/LSO/SinglesDigitizer/Singles/energyFraming/setMax 1300 keV
/gate/digitizerMgr/CoincidenceSorter/Coincidences/setWindow 5. ns
/gate/digitizerMgr/CoincidenceSorter/Coincidences/setOffset 0 ns

# ── Source: Sc-44 confined to the core (material 1) ONLY ──────────────────
/gate/source/addSource sc44_core gps
/gate/source/sc44_core/gps/particle ion
/gate/source/sc44_core/gps/ion 21 44 0 0
/gate/source/sc44_core/gps/ene/type Mono
/gate/source/sc44_core/gps/ene/mono 0 keV
/gate/source/sc44_core/gps/ang/type iso
/gate/source/sc44_core/gps/pos/type Volume
/gate/source/sc44_core/gps/pos/shape Cylinder
/gate/source/sc44_core/gps/pos/radius {r_core} mm
/gate/source/sc44_core/gps/pos/halfz {halfz} mm
/gate/source/sc44_core/gps/pos/centre 0 0 0 mm
/gate/source/sc44_core/gps/pos/confine r2_core_phys
/gate/source/sc44_core/setForcedUnstableFlag true
/gate/source/sc44_core/setForcedHalfLife 14292 s
/gate/source/sc44_core/setActivity 1570000 Bq

/particle/select Sc44
/particle/property/stable false
/particle/property/lifetime 0.001 ns

# ── Output ────────────────────────────────────────────────────────────────
/gate/output/root/enable
/gate/output/root/setFileName r2_{pair}
/gate/output/root/setRootHitFlag 0
/gate/output/root/setRootSinglesFlag 1
/gate/output/root/setRootCoincidencesFlag 1

# ── Run (primaries-controlled, the runner rewrites this line) ─────────────
/gate/application/setTimeStart 0.0 s
/gate/application/setTimeStop  1.0 s
/gate/application/setTimeSlice 1.0 s
/gate/application/setTotalNumberOfPrimaries 1000000

/gate/random/setEngineName MersenneTwister
/gate/random/setEngineSeed 20260813

/gate/application/start
"""


def main():
    HERE.mkdir(parents=True, exist_ok=True)
    quadra = "{PLI_SCANNER_MACRO}"
    mat_main = "{PLI_SIM}/geometry/materials_pli.db"

    for pair, cfg in PAIRS.items():
        txt = MACRO.format(pair=pair, core=cfg["core"], shell=cfg["shell"],
                           r_core=R_CORE_MM, r_shell=R_SHELL_MM,
                           height=HEIGHT_MM, halfz=HEIGHT_MM / 2,
                           quadra=quadra, mat_db_main=mat_main,
                           mat_db_ph2b=PH2B)
        out = HERE / f"core_shell_pair{pair}.mac"
        out.write_text(txt)
        print(f"wrote {out.name}: core {cfg['core']} ({cfg['tau_core']} ns) / "
              f"shell {cfg['shell']} ({cfg['tau_shell']} ns), "
              f"dtau = {abs(cfg['tau_core']-cfg['tau_shell']):.4f} ns")

    # ---- R2a equal-tau materials JSON -------------------------------------
    # Same geometry and the same two materials as R2b pair A, but with tau_eff
    # forced EQUAL. Arms (i) and (ii) then look up different materials that
    # carry the same lifetime, so any difference between them is an artefact
    # of the implementation rather than physics. This is a stronger null test
    # than a single-material phantom, in which the two arms would be identical
    # by construction and could not detect a lookup bug.
    src = json.loads((ROOT / "materials/pli_materials.json").read_text())
    TAU_EQ = 2.0
    n = 0
    for m in src["materials"]:
        names = [m.get("name", "")] + list(m.get("aliases", []) or [])
        if any(x in names for x in (PAIRS["A"]["core"], PAIRS["A"]["shell"])):
            m["tau_TE_ns"] = TAU_EQ
            m["tau_pub_ns"] = TAU_EQ
            m["_r2a_note"] = ("tau forced equal for the R2a null control; "
                              "NOT a physical value")
            n += 1
    src["_r2a_null_control"] = (
        f"tau_TE_ns forced to {TAU_EQ} ns for {PAIRS['A']['core']} and "
        f"{PAIRS['A']['shell']} so that the transport-resolved and "
        f"source-level arms must agree. Generated by make_r2_inputs.py.")
    out = HERE / "r2a_equal_tau_materials.json"
    out.write_text(json.dumps(src, indent=1))
    print(f"wrote {out.name}: {n} material entries forced to tau = {TAU_EQ} ns")
    if n != 2:
        print(f"  WARNING: expected 2 entries, patched {n} — check names")


if __name__ == "__main__":
    main()
